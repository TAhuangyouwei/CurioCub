def normalize(raw):
    """Use ASCII v for ü, and make neutral tone explicit as tone 5."""
    value = raw.replace('ü', 'v').replace('u:', 'v').lower()
    if not re.fullmatch(r'[a-zv]+[1-5]?', value):
        return None
    return value if value[-1].isdigit() else f'{value}5'


def pronunciation_for(character):
    result = pinyin(
        character,
        style=Style.TONE3,
        heteronym=False,
        neutral_tone_with_five=True,
        v_to_u=False,
        errors=lambda _: '',
    )
    if len(result) != 1 or len(result[0]) != 1:
        return None
    return normalize(result[0][0])


def build_content():
    examples = {}
    for codepoint in range(0x4E00, 0x9FFF + 1):
        character = chr(codepoint)
        key = pronunciation_for(character)
        if key and key not in examples:
            examples[key] = character

    examples.update(PREFERRED_EXAMPLES)
    ordered = {key: examples[key] for key in sorted(examples)}
    content = (
        '// Generated by scripts/generate_pinyin_map.py. Do not edit by hand.\n'
        f'const syllableExamples = {json.dumps(ordered, ensure_ascii=True, separators=(",", ":"))}\n\n'
        'module.exports = { syllableExamples }\n'
    )
    return content, len(ordered)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--stdout', action='store_true')
    args = parser.parse_args()
    content, count = build_content()
    if args.stdout:
        print(content, end='')
        return
    target = Path(__file__).resolve().parents[1] / 'data' / 'pinyin-syllables.js'
    target.write_text(content, encoding='utf-8')
    print(f'Generated {count} pinyin-tone examples: {target}')


if __name__ == '__main__':
    main()
