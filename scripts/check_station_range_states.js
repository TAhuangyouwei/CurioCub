const assert = require('assert')
const { orderedHanzi, saveRange } = require('../utils/hanzi-settings')
const { completeUnit, markUnitUnlearned, markUnitUnstudied, getProgress } = require('../utils/progress')
const store = new Map()
let definition
let navigations = 0
global.Page = value => { definition = value }
global.wx = {
  getStorageSync: key => store.get(key),
  setStorageSync: (key, value) => store.set(key, JSON.parse(JSON.stringify(value))),
  setNavigationBarTitle() {}, showToast() {}, navigateTo() { navigations++ }
}
require('../pages/module/module')
const page = { ...definition, data: { ...definition.data }, setData(value) { Object.assign(this.data, value) } }
page.onLoad({ moduleId: 'hanzi' })
const units = orderedHanzi()
saveRange(units[12].id, units[22].id)
page.onShow()
assert.strictEqual(page.data.groups[0].stateLabel, '未开始')
assert(page.data.groups[0].outsideRange)
assert.strictEqual(page.data.groups[1].stateLabel, '未开始', '选中范围不能替代实际学习记录')
assert.strictEqual(page.data.groups[1].startUnitId, units[12].id, '点击进行中从本站范围内首字开始')
assert.strictEqual(page.data.groups[2].stateLabel, '未开始')
assert.strictEqual(page.data.groups[3].stateLabel, '未开始')
const event = index => ({ currentTarget: { dataset: { groupIndex: index } } })
const before = JSON.stringify(getProgress())
page.toggleGroup(event(0))
assert(page.data.groups[0].collapsed, '范围外不能展开')
page.markGroupLearned(event(0))
page.openReview(event(0))
assert.strictEqual(JSON.stringify(getProgress()), before, '范围外不能批量改学习记录')
assert.strictEqual(navigations, 0, '范围外不能进入复习')
completeUnit(units[0].id, 'hanzi')
page.onShow()
assert.strictEqual(page.data.groups[0].stateLabel, '进行中', '范围外部分学过也必须反映真实状态')
assert.strictEqual(page.data.groups[0].percent, 10)
units.slice(0, 8).forEach(unit => completeUnit(unit.id, 'hanzi'))
units.slice(8, 10).forEach(unit => markUnitUnlearned(unit.id, 'hanzi'))
page.onShow()
assert(page.data.groups[0].outsideRange)
assert.strictEqual(page.data.groups[0].percent, 80, '10 个字学会 8 个，应显示 80%，不受范围影响')
assert.strictEqual(page.data.groups[0].unlearned, 2)
assert.strictEqual(page.data.groups[0].unseen, 0)
const learnedBeforeRangeChange = JSON.stringify(getProgress())
saveRange(units[0].id, units[2].id)
page.onShow()
assert.strictEqual(page.data.groups[0].percent, 80, '部分字在范围内，也应按整站计算真实进度')
saveRange(units[12].id, units[22].id)
page.onShow()
assert.strictEqual(JSON.stringify(getProgress()), learnedBeforeRangeChange, '切换范围不改学习记录')
const forbidden = JSON.stringify(getProgress())
page.openGroup(event(0))
page.openReview(event(0))
page.markGroupLearned(event(0))
assert.strictEqual(navigations, 0, '范围外进行中的站点也不能进入学习或复习')
assert.strictEqual(JSON.stringify(getProgress()), forbidden)
markUnitUnlearned(units[0].id, 'hanzi')
page.onShow()
assert.strictEqual(page.data.groups[0].percent, 70, '已学会改为未学会后，进度应立即下降')
units.slice(0, 10).forEach(unit => completeUnit(unit.id, 'hanzi'))
units.slice(10, 20).forEach(unit => completeUnit(unit.id, 'hanzi'))
page.onShow()
assert.strictEqual(page.data.groups[0].stateLabel, '完成', '范围外学完的站保留完成状态')
assert(page.data.groups[0].outsideRange)
assert.strictEqual(page.data.groups[1].stateLabel, '完成', '范围内完成状态优先')
assert.strictEqual(page.data.groups[0].percent, 100)
markUnitUnlearned(units[30].id, 'hanzi')
page.onShow()
assert.strictEqual(page.data.groups[3].stateLabel, '进行中', '只有未学会记录时也不能显示未开始')
assert.strictEqual(page.data.groups[3].percent, 0)
assert.strictEqual(page.data.groups[3].unlearned, 1)
assert.strictEqual(page.data.groups[3].unseen, 9)
markUnitUnstudied(units[30].id, 'hanzi')
const lastUnits = units.slice(-5)
lastUnits.slice(0, 3).forEach(unit => completeUnit(unit.id, 'hanzi'))
page.onShow()
assert.strictEqual(page.data.groups.at(-1).percent, 60, '末站不足十字时，用该站实际字数计算')
page.exitLearningRange()
assert(page.data.groups.every(group => !group.outsideRange), '退出范围后立即恢复可点击状态')
assert.strictEqual(page.data.groups[3].stateLabel, '未开始')
page.onLoad({ moduleId: 'math' })
page.onShow()
assert(page.data.groups.every(group => !group.outsideRange && !group.collapsed), '其他模块不受影响')
console.log('站点范围状态检查通过：未开始/进行中/完成、部分重叠、范围外禁用及退出恢复。')
