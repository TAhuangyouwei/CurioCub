const assert = require('assert')
const { getModule } = require('../data/learning')
const { getProgress, completeUnit, markUnitUnlearned, markUnitUnstudied, getUnitStatus, clearNotebook } = require('../utils/progress')
const { createLessonPage } = require('../pages/lesson/lesson-page')
const store = new Map()
let definition
let modal
global.getApp = () => ({ globalData: { audio: { stop() {} } } })
global.Page = page => { definition = page }
global.wx = {
  getStorageSync: key => key === 'curiocub-hanzi-settings-v1' ? { autoRead: false } : store.get(key),
  setStorageSync: (key, value) => store.set(key, JSON.parse(JSON.stringify(value))),
  showToast() {}, showModal(options) { modal = options }, setNavigationBarTitle() {}
}
function instance(page) {
  return { ...page, data: JSON.parse(JSON.stringify(page.data)), setData(changes) { Object.assign(this.data, changes) } }
}
assert.strictEqual(typeof markUnitUnstudied, 'function')
assert.strictEqual(getUnitStatus('hanzi-01'), 'unseen')
markUnitUnlearned('hanzi-01', 'hanzi')
assert.strictEqual(getUnitStatus('hanzi-01'), 'unlearned')
completeUnit('hanzi-01', 'hanzi')
assert.strictEqual(getUnitStatus('hanzi-01'), 'learned')
const rewards = [getProgress().stars, getProgress().stickerCount]
markUnitUnstudied('hanzi-01', 'hanzi')
assert.strictEqual(getUnitStatus('hanzi-01'), 'unseen')
completeUnit('hanzi-01', 'hanzi')
assert.deepStrictEqual([getProgress().stars, getProgress().stickerCount], rewards, '重置状态不能再次领取奖励')
const lesson = instance(createLessonPage())
lesson.onLoad({ moduleId: 'hanzi', unitId: 'hanzi-01' })
const beforeHint = JSON.stringify(getProgress())
lesson.showHint({ currentTarget: { dataset: { unitId: 'hanzi-01' } } })
assert(lesson.data.hintVisible && lesson.data.completed)
assert.strictEqual(JSON.stringify(getProgress()), beforeHint, '看提示不能改变真实学习状态')
for (const status of ['unseen', 'unlearned', 'learned']) {
  if (status === 'unseen') lesson.markUnstudied()
  if (status === 'unlearned') lesson.markUnlearned()
  if (status === 'learned') lesson.markLearned()
  const before = JSON.stringify(getProgress())
  lesson.showHint({ currentTarget: { dataset: { unitId: 'hanzi-01' } } })
  lesson.showHint({ currentTarget: { dataset: { unitId: 'hanzi-01' } } })
  assert(lesson.data.hintVisible)
  assert.strictEqual(JSON.stringify(getProgress()), before, `${status} 状态反复看图也不能改变生字本或奖励`)
}
lesson.markUnlearned()
assert(!lesson.data.completed && lesson.data.unlearned)
lesson.markUnstudied()
assert(!lesson.data.completed && !lesson.data.unlearned)
assert.strictEqual(getUnitStatus('hanzi-01'), 'unseen')
lesson.markLearned()
markUnitUnlearned('hanzi-02', 'hanzi')
markUnitUnlearned('hanzi-41', 'hanzi')
completeUnit('math-01', 'math')
const beforeClear = getProgress()
require('../pages/notebook/notebook')
const notebook = instance(definition)
notebook.onShow()
assert.strictEqual(notebook.data.items.length, 2)
notebook.clearNotebook()
modal.success({ confirm: false })
assert.strictEqual(notebook.data.items.length, 2, '取消清空不能改记录')
notebook.clearNotebook()
modal.success({ confirm: true })
assert.strictEqual(notebook.data.items.length, 0)
assert.strictEqual(getUnitStatus('hanzi-02'), 'unseen')
assert.strictEqual(getUnitStatus('hanzi-41'), 'unseen')
assert.strictEqual(getUnitStatus('hanzi-01'), 'learned')
assert(getProgress().completedIds['math-01'])
assert.deepStrictEqual(getProgress().rewardedIds, beforeClear.rewardedIds)
assert.strictEqual(getProgress().stars, beforeClear.stars)
assert.strictEqual(getProgress().stickerCount, beforeClear.stickerCount)
clearNotebook(['hanzi-01'])
assert.strictEqual(getUnitStatus('hanzi-01'), 'learned', '清空不能重置已学会的字')
require('../pages/module/module')
const map = instance(definition)
map.onLoad({ moduleId: 'hanzi' })
map.onShow()
assert.strictEqual(map.data.learnedCount, 1)
assert.strictEqual(map.data.unlearnedCount, 0)
assert.strictEqual(map.data.unseenCount, getModule('hanzi').items.length - 1)
console.log('三种学习状态检查通过：互相切换、提示不改状态、清空/取消、保留已学会及奖励、状态统计。')
