const assert = require('assert')
const { getModule } = require('../data/learning')
const { characters, defaultOrder } = require('../data/hanzi-school')
const store = new Map()
global.wx = {
  getStorageSync: key => store.get(key),
  setStorageSync: (key, value) => store.set(key, JSON.parse(JSON.stringify(value)))
}
const { orderedHanzi, saveOrder, getHanziSettings, saveRange, studyUnits, exitRange, setAutoRead } = require('../utils/hanzi-settings')
const units = getModule('hanzi').items
assert.strictEqual(characters.length, 56)
assert.strictEqual(units.length, 475)
const ordered = orderedHanzi()
assert.strictEqual(ordered[77].title, '许')
const first = new Set(units.slice(0, 78).map(unit => unit.title))
const inserted = [...characters].filter(char => !first.has(char))
assert.strictEqual(inserted.length, 53)
assert.strictEqual(ordered.slice(78, 131).map(unit => unit.title).join(''), inserted.join(''))
assert.strictEqual(ordered[131].title, '数')
assert.strictEqual(new Set(ordered.map(unit => unit.id)).size, 475)
assert.deepStrictEqual(ordered.slice(0, 78), units.slice(0, 78), '原有前 78 字的位置与内容应保留')
assert.strictEqual(units[78].id, 'hanzi-79', '排序不能修改资源和学习记录编号')
assert.deepStrictEqual(studyUnits(units), ordered)
const changed = ordered.slice()
changed.unshift(changed.splice(changed.findIndex(unit => unit.title === '电'), 1)[0])
setAutoRead(false)
assert(saveOrder(changed.map(unit => unit.id)))
assert.deepStrictEqual(orderedHanzi(), changed)
assert.strictEqual(getHanziSettings().autoRead, false)
assert.strictEqual(saveOrder([units[0].id]), false, '不能保存缺字的顺序')
assert.strictEqual(saveOrder(changed.map(() => units[0].id)), false, '不能保存重复编号')
assert(saveRange(ordered[78].id, ordered[80].id))
assert.deepStrictEqual(studyUnits(units), ordered.slice(78, 81), '范围应按屏幕顺序选取')
// Moving a saved endpoint must keep the range valid regardless of direction.
const reversed = changed.slice().reverse()
assert(saveOrder(reversed.map(unit => unit.id)))
assert(getHanziSettings().rangeEnabled)
assert.strictEqual(studyUnits(units).length, 3)
exitRange()
assert.deepStrictEqual(orderedHanzi(), reversed)
assert(saveOrder([]), '空顺序表示恢复默认')
assert.deepStrictEqual(orderedHanzi(), defaultOrder(units))
assert.strictEqual(store.has('curiocub-progress-v1'), false, '调整顺序不能改写学会状态、星星或生字本')
console.log('识字排序检查通过：53 字插入许数之间、475 个稳定编号、自定义/恢复、范围与进度隔离。')
