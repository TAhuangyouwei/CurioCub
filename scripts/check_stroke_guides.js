const assert = require('assert')
const guides = require('../packages/hanzi-practice/data/stroke-guides')
const { getModule } = require('../data/learning')
const { guideFor, pointAlong } = require('../packages/hanzi-practice/utils/stroke-guide')
for (const unit of getModule('hanzi').items) {
  const guide = guideFor(unit.title)
  assert(guide && guide.count > 0, `${unit.title} 缺少首笔数据`)
  assert(guide.points.length >= 2)
  for (const point of guide.points) assert(point.every((value) => value > 0 && value < 1000), `${unit.title} 引导越界`)
  assert(Number.isFinite(guide.angle))
  assert.deepStrictEqual(pointAlong(guide.points, 0), guide.points[0])
  assert.deepStrictEqual(pointAlong(guide.points, 1), guide.points.at(-1))
}
assert.strictEqual(Object.keys(guides).length, 458)
assert.strictEqual(guideFor('虫').count, 6)
assert(guideFor('虫').points.at(-1)[1] > guideFor('虫').points[0][1], '虫的第一笔应向下，不能从中间长竖开始')
assert(guideFor('虫').angle > 45 && guideFor('虫').angle < 90, '虫的起笔箭头不能被笔锋误导为横向')
assert(guideFor('一').points.at(-1)[0] > guideFor('一').points[0][0])
assert(guideFor('手').angle > 90 && guideFor('手').angle < 180, '撇的箭头不能跟着笔锋朝左上方')
assert(Math.abs(guideFor('上').angle - 90) < 15, '竖的箭头应朝下')
assert(Math.abs(guideFor('刀').angle) < 30, '横折钩的箭头应先横向，不能直接斜向钩尾')
assert.strictEqual(guideFor('unknown'), null)
console.log('首笔引导检查通过：458 字、真实笔顺首笔、楷体坐标、方向、边界与匀速演示。')
