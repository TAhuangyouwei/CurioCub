const assert = require('assert')
const { orderedHanzi, getHanziSettings, saveRange } = require('../utils/hanzi-settings')
const { getModule } = require('../data/learning')
const { createLessonPage } = require('../pages/lesson/lesson-page')
const { createReviewPage } = require('../pages/review/review-page')
const store = new Map()
let definition, navigation, modal
global.Page = value => { definition = value }
global.getApp = () => ({ globalData: { audio: { stop() {} } } })
global.wx = {
  getStorageSync: key => store.get(key),
  setStorageSync: (key, value) => store.set(key, JSON.parse(JSON.stringify(value))),
  navigateTo: options => { navigation = options.url }, navigateBack: () => { navigation = 'back' },
  redirectTo: options => { navigation = options.url }, setNavigationBarTitle() {}, showToast() {},
  showModal: options => { modal = options }, getWindowInfo: () => ({ windowWidth: 375 })
}
function instance(value) {
  return { ...value, data: JSON.parse(JSON.stringify(value.data)), setData(value) { Object.assign(this.data, value) } }
}
require('../pages/learning-order/learning-order')
const editor = instance(definition)
editor.onLoad()
editor.search({ detail: { value: '竹叶草' } })
assert.strictEqual(editor.data.units.filter(unit => !unit.hidden).length, 3)
const original = orderedHanzi()
const electric = original.find(unit => unit.title === '电')
const bird = original.find(unit => unit.title === '鸟')
const toggle = id => editor.toggleCharacter({ currentTarget: { dataset: { id } } })
toggle(electric.id)
toggle(bird.id)
assert.deepStrictEqual(editor.data.selected.map(unit => unit.id), [electric.id, bird.id])
toggle(bird.id)
toggle(bird.id)
assert(!editor.data.destinations.some(unit => unit.id === electric.id), '选中的字不能作为自己的移动目标')
editor.changeDestination({ detail: { value: 0 } })
editor.save()
assert.strictEqual(navigation, 'back')
assert.deepStrictEqual(orderedHanzi().slice(0, 2).map(unit => unit.id), [electric.id, bird.id])
require('../pages/module/module')
const map = instance(definition)
map.onLoad({ moduleId: 'hanzi' })
map.onShow()
assert.strictEqual(map.data.groups[0].items[0].id, electric.id)
map.editOrder()
assert.strictEqual(navigation, '/pages/learning-order/learning-order')
map.startRangeLearning()
assert(navigation.includes(electric.id))
store.set('curiocub-hanzi-settings-v1', { ...getHanziSettings(), autoRead: false })
const lesson = instance(createLessonPage())
lesson.onLoad({ moduleId: 'hanzi', unitId: electric.id })
assert.strictEqual(lesson.lessonItems[1].id, bird.id)
const review = instance(createReviewPage())
review.onLoad({ moduleId: 'hanzi', groupIndex: 0 })
assert.deepStrictEqual(review.reviewUnits.map(unit => unit.id), orderedHanzi().slice(0, 10).map(unit => unit.id))
const { getToday } = require('../packages/hanzi-practice/utils/session')
const progress = { completedIds: {}, unlearnedIds: {} }
const today = getToday(progress, '2026-10-27')
assert.deepStrictEqual(today.cards.map(card => card.id), orderedHanzi().slice(0, 3).map(unit => unit.id), '新生成的每日任务应优先采用家长顺序')
saveRange(electric.id, bird.id)
require('../pages/learning-range/learning-range')
const range = instance(definition)
range.onLoad()
assert.strictEqual(range.data.rangeStart, 0)
assert.strictEqual(range.data.rangeEnd, 1)
editor.restoreDefault()
modal.success({ confirm: false })
assert.strictEqual(orderedHanzi()[0].id, electric.id)
editor.restoreDefault()
modal.success({ confirm: true })
assert.deepStrictEqual(orderedHanzi(), original)
assert.deepStrictEqual(getToday(progress, '2026-10-27'), today, '排序变化不应打乱已经生成的每日任务')
assert.strictEqual(store.has('curiocub-progress-v1'), false)
assert.strictEqual(getModule('hanzi').items[0].id, 'hanzi-01')
console.log('排序页面检查通过：搜索/点选顺序、移动目标、保存/恢复、地图、卡片、配对与范围一致。')
